/**
 * Founder approval — step 3 of the creative review workflow.
 *
 * Promotes one reviewed candidate into the premium media library. This is the only path by which
 * an image becomes a brand asset: nothing reaches public/media/premium/ without a Founder
 * selection recorded here.
 *
 * Usage:
 *   node scripts/media/approve-selection.mjs <brief-id> <candidate-number> [--replace] [--note "..."]
 *
 * An already-approved asset is never overwritten silently. --replace is the explicit approval to
 * retire the incumbent, and the previous entry is kept in the manifest's `superseded` history so
 * the brand's visual decisions stay auditable.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import sharp from "sharp";

import {
  CANDIDATES_DIR,
  MANIFEST_PATH,
  assetFilePath,
  assetPublicPath,
  download,
  minimumWidth,
  resolveBrief,
  resolveSection,
} from "./lib/acquire.mjs";
import { notifyProviderDownload } from "./lib/providers.mjs";

const GENERATED_TS = join("src", "config", "media", "premium-manifest.generated.ts");
const MASTER_WIDTH = 2560;

/**
 * The photograph's dominant colours, for the brand moodboard.
 *
 * Extracted here because this is the one place the master is already decoded — doing it at render
 * time would mean either shipping an image codec into the application or re-reading every approved
 * file on every page load, and doing it in a separate pass would mean a palette that can fall out of
 * step with the image it describes.
 *
 * The method is deliberately crude: shrink to a small grid, quantise, and count. It is not trying to
 * be a colour-theory tool. It answers one question — do these eight photographs belong to the same
 * brand, or is one of them a different product — and for that, the honest average of a frame is more
 * useful than its most striking accent.
 */
async function extractPalette(buffer) {
  const SIDE = 24;
  const { data } = await sharp(buffer)
    .resize(SIDE, SIDE, { fit: "cover" })
    .removeAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  /* Quantise to a 6-level cube per channel: enough to separate navy from teal, coarse enough that
     compression noise and film grain do not each become their own "colour". */
  const buckets = new Map();
  for (let i = 0; i < data.length; i += 3) {
    const key = [data[i], data[i + 1], data[i + 2]]
      .map((channel) => Math.min(5, Math.round((channel / 255) * 5)))
      .join(",");
    const bucket = buckets.get(key) ?? { count: 0, r: 0, g: 0, b: 0 };
    bucket.count += 1;
    bucket.r += data[i];
    bucket.g += data[i + 1];
    bucket.b += data[i + 2];
    buckets.set(key, bucket);
  }

  const total = data.length / 3;
  const hex = (value) => Math.round(value).toString(16).padStart(2, "0");

  return [...buckets.values()]
    .sort((a, b) => b.count - a.count)
    .slice(0, 5)
    .map((bucket) => ({
      hex: `#${hex(bucket.r / bucket.count)}${hex(bucket.g / bucket.count)}${hex(bucket.b / bucket.count)}`,
      share: Math.round((bucket.count / total) * 100),
    }));
}

const readManifest = () =>
  existsSync(MANIFEST_PATH) ? JSON.parse(readFileSync(MANIFEST_PATH, "utf8")) : { assets: {} };

function parseArgs(argv) {
  const positional = argv.filter((a) => !a.startsWith("--"));
  const noteIndex = argv.indexOf("--note");
  return {
    briefId: positional[0],
    candidateNumber: Number(positional[1]),
    replace: argv.includes("--replace"),
    note: noteIndex === -1 ? null : argv[noteIndex + 1] ?? null,
  };
}

/** Emits the typed module the application imports. Never hand-edit the output. */
function writeGeneratedModule(manifest) {
  const entries = Object.entries(manifest.assets).sort(([a], [b]) => a.localeCompare(b));

  const body = entries
    .map(([id, asset]) => `  ${JSON.stringify(id)}: ${JSON.stringify(asset, null, 2).replace(/\n/g, "\n  ")},`)
    .join("\n");

  writeFileSync(
    GENERATED_TS,
    `/**
 * GENERATED by scripts/media/approve-selection.mjs — do not edit by hand.
 *
 * Every entry here is a Founder-approved brand asset. Re-run the approval script to change one.
 */

export const PREMIUM_MEDIA_MANIFEST = {
${body}
} as const;

export type PremiumMediaId = keyof typeof PREMIUM_MEDIA_MANIFEST;
`,
  );
}

async function main() {
  const { briefId, candidateNumber, replace, note } = parseArgs(process.argv.slice(2));

  if (!briefId || !Number.isInteger(candidateNumber)) {
    console.error(
      "Usage: node scripts/media/approve-selection.mjs <brief-id> <candidate-number> [--replace] [--note \"...\"]",
    );
    process.exit(1);
  }

  const brief = resolveBrief(briefId);
  const boardPath = join(CANDIDATES_DIR, briefId, "candidates.json");
  if (!existsSync(boardPath)) {
    throw new Error(`No candidate board for "${briefId}". Run the acquisition step first.`);
  }

  const board = JSON.parse(readFileSync(boardPath, "utf8"));
  const candidate = board.candidates.find((c) => c.index === candidateNumber);
  if (!candidate) {
    throw new Error(
      `Candidate ${candidateNumber} not on the ${briefId} board (1–${board.candidates.length}).`,
    );
  }

  const manifest = readManifest();
  const incumbent = manifest.assets[briefId];
  if (incumbent && !replace) {
    throw new Error(
      `“${brief.title}” is already approved: ${incumbent.title}. Approved media is part of the brand — ` +
        "retire it deliberately (--replace on the CLI, or the replace disclosure on the review board).",
    );
  }

  const section = resolveSection(briefId);

  /** In-house briefs approve a treatment, not a photograph — there is no file to promote. */
  const isInHouse = brief.acquisition === "in-house";
  let asset;

  if (isInHouse) {
    asset = {
      id: briefId,
      section: section.id,
      kind: "treatment",
      title: candidate.title,
      treatment: String(candidate.generator ?? "").split("#")[1] ?? null,
      src: null,
      width: null,
      height: null,
      licence: candidate.licence,
      licenceUrl: null,
      requiresAttribution: false,
      author: candidate.author,
      sourceUrl: null,
    };
  } else {
    console.log(`Fetching master — ${candidate.title}`);
    const buffer = await download(candidate.masterUrl);

    /**
     * Unsplash's API terms require telling them when a photograph is actually taken, so the download
     * is counted for the photographer. Approval is that moment: it is the point at which the frame
     * stops being a candidate and becomes ours. Best-effort — see notifyProviderDownload.
     */
    await notifyProviderDownload(candidate);

    /**
     * The last check before an image becomes part of the brand: is the file we were actually handed
     * big enough for the slot?
     *
     * Boards record what the archive claims, and archives over-claim — StockSnap reports 8192px and
     * serves 960px. Acquisition now verifies this up front, but a board shortlisted before that
     * still holds the old claim, and a soft hero is exactly the kind of defect nobody notices in
     * review and everybody notices on the homepage. Refusing here means it cannot happen at all.
     */
    const actual = await sharp(buffer).metadata();
    const required = minimumWidth(brief);
    if (!actual.width || actual.width < required) {
      /* Thrown rather than exited: sharp's worker threads are still live here, and tearing the
         process down underneath them trips a libuv assertion instead of printing the reason. */
      throw new Error(
        [
          `Candidate ${candidateNumber} cannot be approved — the master delivered is too small for this slot.`,
          `Delivered ${actual.width ?? "?"}×${actual.height ?? "?"}; this slot needs at least ${required}px wide.`,
          candidate.width && candidate.width !== actual.width
            ? `The board reports ${candidate.width}×${candidate.height}, so the source over-claims its resolution.`
            : null,
          "Choose another candidate, or re-run the shortlist to refresh this board.",
        ]
          .filter(Boolean)
          .join(" "),
      );
    }

    const destination = assetFilePath(briefId);
    mkdirSync(dirname(destination), { recursive: true });

    const { width, height } = await sharp(buffer)
      .resize({ width: MASTER_WIDTH, withoutEnlargement: true })
      .webp({ quality: 84 })
      .toFile(destination);

    asset = {
      id: briefId,
      section: section.id,
      kind: "photograph",
      title: candidate.title,
      src: assetPublicPath(briefId),
      width,
      height,
      palette: await extractPalette(buffer),
      licence: candidate.licence,
      licenceUrl: candidate.licenceUrl,
      requiresAttribution: candidate.requiresAttribution,
      author: candidate.author,
      authorUrl: candidate.authorUrl ?? null,
      provider: candidate.providerLabel ?? candidate.provider ?? null,
      sourceUrl: candidate.sourceUrl,
    };
  }

  manifest.assets[briefId] = {
    ...asset,
    /** Which frame on the board this was, so an approval can be traced back to what was reviewed. */
    candidateIndex: candidateNumber,
    brief: { title: brief.title, emotion: brief.emotion },
    approvedOn: new Date().toISOString().slice(0, 10),
    approvalNote: note,
    ...(incumbent
      ? { superseded: [...(incumbent.superseded ?? []), { ...incumbent, superseded: undefined }] }
      : {}),
  };

  mkdirSync(dirname(MANIFEST_PATH), { recursive: true });
  writeFileSync(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`);
  writeGeneratedModule(manifest);

  console.log(`\nApproved — ${brief.title}`);
  console.log(`  ${asset.title}`);
  console.log(`  ${asset.licence}${asset.requiresAttribution ? "  (attribution required, and wired)" : ""}`);
  if (asset.src) console.log(`  ${asset.src}  ${asset.width}×${asset.height}`);
  console.log(`  manifest: ${MANIFEST_PATH}`);
}

/**
 * `process.exitCode`, not `process.exit()`. Sharp keeps worker threads alive across an await, and
 * tearing the process down underneath them trips a libuv assertion that buries the actual message
 * and returns 127 instead of 1 — which the review dashboard would then report as a crash rather
 * than as the refusal it is. Setting the code lets Node drain and exit on its own.
 */
main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
