/**
 * Vehicle Media Intelligence — review report.
 *
 * Scores every photograph of every vehicle in the demonstration library and reports which frame *should*
 * lead each listing against which one currently does. It writes two files and changes nothing else:
 * production records are not touched, and no primary photograph is reassigned. Recommendations go to a
 * person first, which is the whole point.
 *
 * The scorer is imported straight from `src/services/media-intelligence/photo-scorer.ts` — Node strips
 * the types — so this report and the application cannot reach different verdicts. Weights and thresholds
 * exist in exactly one file.
 *
 * Usage:
 *   node scripts/media/score-vehicle-photos.mjs
 *   node scripts/media/score-vehicle-photos.mjs --vehicle volvo-xc90     # one vehicle, verbose
 */
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { categoryFromViewName, extractPhotoFeatures } from "./lib/photo-features.mjs";
import { resolvePrimaryPhoto, scorePhoto } from "../../src/services/media-intelligence/photo-scorer.ts";

const LIBRARY_DIR = join("public", "images", "vehicles", "library");
const OUT_DIR = join("docs", "reports");
const REPORT_MD = join(OUT_DIR, "vehicle-media-intelligence.md");
const REPORT_JSON = join(OUT_DIR, "vehicle-media-intelligence.json");

/**
 * The frame the product currently leads with.
 *
 * Listing photography is stored per vehicle as `<slug>/<view>.webp`, and `front` is the convention the
 * records follow. It is stated here rather than read from the database on purpose: this report's job is
 * to be runnable by anyone, against files, without credentials.
 */
const CURRENT_PRIMARY_VIEW = "front";

const args = process.argv.slice(2);
const onlyVehicle = args.includes("--vehicle") ? args[args.indexOf("--vehicle") + 1] : null;

const listVehicles = () =>
  readdirSync(LIBRARY_DIR)
    .filter((entry) => statSync(join(LIBRARY_DIR, entry)).isDirectory())
    .filter((entry) => !onlyVehicle || entry === onlyVehicle)
    .sort();

async function scoreVehicle(slug) {
  const dir = join(LIBRARY_DIR, slug);
  const files = readdirSync(dir).filter((file) => /\.(webp|jpe?g|png)$/i.test(file));
  if (files.length === 0) return null;

  const photos = files.map((file) => ({ id: file.replace(/\.[^.]+$/, "") }));
  const scores = [];

  for (const file of files) {
    const id = file.replace(/\.[^.]+$/, "");
    try {
      const category = categoryFromViewName(id);
      scores.push(scorePhoto(await extractPhotoFeatures(join(dir, file), id, category)));
    } catch (error) {
      console.log(`  ! ${slug}/${file}: ${error.message}`);
    }
  }

  if (scores.length === 0) return null;

  const decision = resolvePrimaryPhoto({ photos, scores });
  const current = scores.find((score) => score.id === CURRENT_PRIMARY_VIEW) ?? null;
  const recommended = scores.find((score) => score.id === decision.id) ?? null;

  return {
    vehicle: slug,
    currentPrimary: current ? current.id : "(none)",
    currentScore: current?.score ?? null,
    recommendedPrimary: decision.id,
    recommendedScore: recommended?.score ?? null,
    /* The gain is what makes a recommendation worth acting on. A two-point difference is noise. */
    delta: current && recommended ? recommended.score - current.score : null,
    reason: decision.reason,
    confidence: decision.confidence,
    runnerUp: decision.runnerUpId,
    changed: current ? decision.id !== current.id : true,
    scores: scores.sort((a, b) => b.score - a.score),
  };
}

const escapePipes = (value) => String(value).replace(/\|/g, "\\|");

function buildMarkdown(rows) {
  const changed = rows.filter((row) => row.changed);
  const material = changed.filter((row) => (row.delta ?? 0) >= 8);

  const lines = [
    "# Vehicle Media Intelligence — review report",
    "",
    "_Generated by `npm run media:score`. Nothing in this report has been applied._",
    "",
    "Every listing should lead with its strongest photograph rather than whichever file was uploaded",
    "first. This report scores each vehicle's frames on composition and technical quality and names the",
    "one that should be primary. **No production record has been modified.**",
    "",
    "## What the scorer can and cannot see",
    "",
    "**There is no object detection here.** The scorer cannot confirm that a vehicle fills the frame or",
    "that all of it is visible. An earlier version tried to infer that from where a frame's detail lived,",
    "and against this very library it recommended a photograph of police officers in a car park — because",
    "a car that fills the frame puts its own contours at the edges, and because a glossy car body is",
    "smoother than grass. Edge statistics rank a distant flat car park above a close, well-lit car.",
    "",
    "So the scorer uses what is actually *known*. Every photograph carries the category it was uploaded",
    "under — exterior, interior, wheels, engine — so whether a frame shows the whole car or its gearbox is",
    "a fact rather than a guess. Category decides which frames may lead at all. Pixel measurements then",
    "rank the eligible ones on what pixels can honestly report: visual noise, acuity, exposure, contrast,",
    "shape and resolution.",
    "",
    "The remaining gap is real and is not papered over: between two well-formed exterior photographs, this",
    "ranks on background calm and technical quality, which is weaker than a person's eye. When the top two",
    "are close, confidence collapses.",
    "",
    "**Low confidence is not a defect in the report — it is the report asking you to look.**",
    "",
    "## Summary",
    "",
    `- Vehicles scored: **${rows.length}**`,
    `- Recommendations differing from the current primary: **${changed.length}**`,
    `- Of those, a material improvement (8+ points): **${material.length}**`,
    "",
    "## Recommendations",
    "",
    "| Vehicle | Current primary | Recommended | Gain | Confidence | Reason |",
    "| --- | --- | --- | --- | --- | --- |",
  ];

  for (const row of [...rows].sort((a, b) => (b.delta ?? -99) - (a.delta ?? -99))) {
    const gain = row.delta === null ? "—" : row.delta > 0 ? `+${row.delta}` : String(row.delta);
    lines.push(
      `| ${escapePipes(row.vehicle)} | ${escapePipes(row.currentPrimary)}${
        row.currentScore === null ? "" : ` (${row.currentScore})`
      } | ${escapePipes(row.recommendedPrimary)}${
        row.recommendedScore === null ? "" : ` (${row.recommendedScore})`
      } | ${gain} | ${row.confidence.toFixed(2)} | ${escapePipes(row.reason)} |`,
    );
  }

  lines.push(
    "",
    "## Applying a recommendation",
    "",
    "Precedence is Founder, then dealer, then scorer, then upload order — see `resolvePrimaryPhoto`. A",
    "Founder or dealer choice is permanent and the scorer never revises it, because an override that can",
    "be overruled is advice, not a decision.",
    "",
  );

  return lines.join("\n");
}

async function main() {
  if (!existsSync(LIBRARY_DIR)) {
    throw new Error(`No vehicle library at ${LIBRARY_DIR}.`);
  }

  const vehicles = listVehicles();
  if (vehicles.length === 0) {
    throw new Error(onlyVehicle ? `No vehicle directory "${onlyVehicle}".` : "No vehicles found.");
  }

  console.log(`Scoring ${vehicles.length} vehicle${vehicles.length === 1 ? "" : "s"}…\n`);

  const rows = [];
  for (const slug of vehicles) {
    const row = await scoreVehicle(slug);
    if (!row) continue;
    rows.push(row);

    const marker = row.changed ? (row.delta ?? 0) >= 8 ? "→" : "·" : " ";
    console.log(
      `${marker} ${slug.padEnd(26)} ${String(row.currentPrimary).padEnd(10)} → ${String(
        row.recommendedPrimary,
      ).padEnd(10)} ${row.delta === null ? "" : `${row.delta > 0 ? "+" : ""}${row.delta}`.padStart(4)}  conf ${row.confidence.toFixed(2)}`,
    );

    if (onlyVehicle) {
      for (const score of row.scores) {
        console.log(`    ${String(score.id).padEnd(11)} ${String(score.score).padStart(3)}  ${score.reason}`);
        for (const fault of score.disqualifiers) console.log(`        ✗ ${fault}`);
      }
    }
  }

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(REPORT_MD, buildMarkdown(rows));
  writeFileSync(REPORT_JSON, `${JSON.stringify({ generatedFor: "vehicle-library", rows }, null, 2)}\n`);

  const changed = rows.filter((row) => row.changed).length;
  const material = rows.filter((row) => row.changed && (row.delta ?? 0) >= 8).length;

  console.log(`\n${rows.length} vehicles scored — ${changed} differ from the current primary, ${material} materially.`);
  console.log(`Report: ${REPORT_MD}`);
  console.log("Nothing has been applied. Review the report and choose.");
}

main().catch((error) => {
  console.error(`\n${error.message}`);
  process.exitCode = 1;
});
